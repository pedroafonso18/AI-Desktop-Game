// Generates src/fonts.css with base64-embedded woff2 fonts so the game runs
// from file:// with no network and no CORS issues.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const fonts = [
  { file: 'silkscreen-latin.woff2', family: 'Silkscreen', weight: 400, range: 'U+0000-00FF' },
  { file: 'silkscreen-latin-ext.woff2', family: 'Silkscreen', weight: 400, range: 'U+0100-024F' },
  { file: 'silkscreen-bold-latin.woff2', family: 'Silkscreen', weight: 700, range: 'U+0000-00FF' },
  { file: 'pressstart2p-latin.woff2', family: 'PressStart2P', weight: 400, range: 'U+0000-00FF' },
  { file: 'pressstart2p-latin-ext.woff2', family: 'PressStart2P', weight: 400, range: 'U+0100-024F' },
];

let css = '/* Auto-generated by tools/embed-fonts.js - do not edit by hand. */\n';
for (const f of fonts) {
  const p = path.join(root, 'assets', 'fonts', f.file);
  const b64 = fs.readFileSync(p).toString('base64');
  css += `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:block;` +
    `src:url(data:font/woff2;base64,${b64}) format('woff2');unicode-range:${f.range};}\n`;
}
fs.writeFileSync(path.join(root, 'src', 'fonts.css'), css);
console.log('wrote src/fonts.css', (css.length / 1024).toFixed(1) + 'kb');
